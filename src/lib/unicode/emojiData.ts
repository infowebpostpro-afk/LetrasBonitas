// Search function for emojis
export function searchEmojis(
  query: string,
  category: EmojiCategory | 'todos' = 'todos'
): Emoji[] {
  const normalizedQuery = query.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  
  if (!normalizedQuery) {
    // Return all emojis if no query
    if (category === 'todos') return EMOJIS;
    return EMOJIS.filter(e => e.category === category);
  }

  return EMOJIS.filter(emoji => {
    // Category filter
    if (category !== 'todos' && emoji.category !== category) return false;

    // Search in emoji character itself
    if (emoji.char.includes(query)) return true;

    // Search in Spanish name
    const normalizedName = emoji.nameEs.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (normalizedName.includes(normalizedQuery)) return true;

    // Search in aliases
    const normalizedAliases = emoji.aliases.map(a => 
      a.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    );
    if (normalizedAliases.some(a => a.includes(normalizedQuery))) return true;

    // Search in emotions
    const normalizedEmotions = emoji.emotions.map(e => 
      e.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    );
    if (normalizedEmotions.some(e => e.includes(normalizedQuery))) return true;

    return false;
  });
}

// Get related emojis based on shared emotions or category
export function getRelatedEmojis(emoji: Emoji, limit: number = 8): Emoji[] {
  const related = EMOJIS.filter(e => 
    e.id !== emoji.id && (
      e.category === emoji.category ||
      e.emotions.some(em => emoji.emotions.includes(em))
    )
  );
  
  // Shuffle and limit
  return related.sort(() => Math.random() - 0.5).slice(0, limit);
}

// Apply skin tone modifier to emoji if supported
export function applySkinTone(emoji: Emoji, skinToneChar: string): string {
  if (!emoji.skinToneSupport || !skinToneChar) return emoji.char;
  
  // Remove existing skin tone modifiers if any
  const baseChar = emoji.char.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, '');
  
  // Apply new skin tone
  return baseChar + skinToneChar;
}
